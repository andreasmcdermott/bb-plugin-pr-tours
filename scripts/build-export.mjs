import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
const result = await build({
  entryPoints: ["viewer/main.tsx"],
  bundle: true,
  minify: true,
  write: false,
  platform: "browser",
  format: "iife",
  target: "es2022",
  define: { "process.env.NODE_ENV": '"production"' },
  outdir: "dist/export",
});
const js = result.outputFiles
  .find((file) => file.path.endsWith(".js"))
  .text.replaceAll("</script", "<\\/script");
const css = result.outputFiles
  .find((file) => file.path.endsWith(".css"))
  .text.replaceAll("</style", "<\\/style");
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>PR Tour</title><style>html,body,#root{height:100%;margin:0}${css}</style></head><body><div id="root"></div><script>${js}</script></body></html>`;
await mkdir("generated", { recursive: true });
await writeFile(
  "generated/export-template.ts",
  `// Generated by scripts/build-export.mjs.\nexport const exportTemplate = ${JSON.stringify(html)};\n`,
);
console.log(`Built standalone viewer (${Math.round(html.length / 1024)} KiB)`);
